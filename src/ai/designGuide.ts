export const DESIGN_GUIDE = `## 敘事設計準則（請逐條遵守）
### A. 結構與分支
A1 用「分支與瓶頸」當骨架：每章是一段主線，章內的分支在章末的瓶頸會合；會合點至少一句台詞依先前分支不同。
A2 禁止整局時間洞穴：分支最多 2 層就要會合，只有最終章的結局段落可以完全分開。
A3 後果記在開關或變數上：每個主要選擇打開一個有名稱的開關；後續事件頁條件、條件分支與結局讀取它。每個打開的開關都至少被讀取 1 次。
A4 蒐集型步驟不限順序；每個狀態都走得到下一步，不會卡關。
### B. 選擇設計
B1 選擇要有意圖：玩家選之前看得出利害、方向與代價，不做盲選。
B2 每章至少一個真正的兩難：兩邊都是玩家在乎的東西，沒有明顯正解，雙方立場說明量相近。
B3 選項彼此在語氣、意圖或價值上不同，並回應上一句話，不要全是問句。
B4 主要選擇全局 4～8 個（每章 1～2 個），放在戲劇高點；其他是風味選擇，但也要換到一句專屬回應。
B5 每個主要選擇都要在「後續章節的某段對話」與「結局或尾聲」中各被回應一次。
### C. 任務設計
C1 每個任務一個終點，寫清楚交付者、他為什麼在乎、完成條件；任務日誌的步驟寫出「找誰／去哪／做什麼」。
C2 不做單純跑腿：每個任務至少 1 個轉折或新資訊，改變玩家知道的事或想做的事。
C3 每個物品都要有敘事脈絡，並在對話或條件中被用到；不加無意義的系統。
C4 相鄰步驟換人或換地點；每章至少 1 個步驟有 2 種解法（例如說服或交出物品），各有台詞。
### D. 人物與對話
D1 每位角色有一句話說得出的「想要什麼」與「秘密」、固定的說話特徵（用詞、句長、口頭禪），寫在角色設定，並牽涉任務或結局。
D2 對話圍繞玩家的目標推進，人物不要只自我介紹。
D3 每則文字 2～3 句；關鍵資訊不放第一句；重大揭露後給玩家回應選項。
D4 不重複資訊；主要人物用多個事件頁依劇情進度說不同的話，讓人覺得「他記得我做過的事」。
D5 長對話要有一個直接推進主線的選項。
### E. 節奏（1～2 小時）
E1 全長 60～120 分鐘，分 4～6 章，每章 10～25 分鐘；時長來自內容，不靠拉長走路距離或重複對話。
E2 關鍵資訊用專屬事件傳達；情感高點前後留一個短的停頓（獨白、風景、安靜的對話）。
E3 交給環境說的就不用台詞說：每章至少 3 個可調查的事件（告示、日記、遺物、景色）分擔背景與伏筆。
### F. 結局
F1 結局由至少 2 個開關或狀態的組合決定，不能只看最後一個選擇。
F2 結局文字點名回應至少 2 個玩家做過的決定（可用尾聲）；各結局在意義上不同（誰得到什麼、付出什麼），不是同一結果的好壞版本。
F3 結局回答開場的主要問題，並交代每位主要角色的去向（各至少一句）。
### G. 互動回饋（降低迷失感）
G1 主要路線旁要有可調查的事件，調查後給背景、線索或幽默的回應。
G2 被鎖住或還不能做的事一定要有回饋並提示解法：例如「門鎖著，鎖孔上刻著守林人的記號」，取得條件後用下一個事件頁換成新的回應。
G3 玩家隨時知道下一步：任務日誌的目前步驟、人物在任務進行中的事件頁都要再次提示目的地。
G4 回應要有個性：同一個事件在不同狀態下的回應要不同，避免只寫「這是一扇門」。
### H. 長篇與章節（前輩方法；出處見 docs/narrative-design-guide.md 的 R1～R20）
H1 開場幾分鐘內，由角色說出最終目標與第一個小目標；玩家要知道「我是誰、想要什麼、現在該做什麼」。〔R1, R12〕
H2 主線從小目標開始，一章一章擴大範圍與賭注（個人 → 關係 → 群體或信念）；不要一開場就拯救世界，也不要每章重複同一種衝突。〔R13, R17〕
H3 每章圍繞一個主題或互動方式，事件依「起：介紹 → 承：加深 → 轉：意外變化 → 合：讓玩家運用學到的」安排。〔R3〕
H4 每章結尾有一個收束點（各條線索在這裡會合），收束之後接一個懸念或揭露，把玩家帶進下一章（「章節」指令與標題卡）。〔R2, R17〕
H5 驚喜與反轉來自外部世界（局勢、人物的真面目），不要讓主角突然做出違背玩家意志的事。〔R18〕
H6 中段至少一次「原以為的真相被推翻」，而且回頭能在前面的章節找到伏筆。〔R18, R17, R6〕
H7 每章同時開放 2～3 條互不依賴的調查線（不限順序），再收斂到同一個關卡；不要一條線一路卡到底。〔R1, R2〕
H8 每個謎題或任務步驟都要推進劇情或揭露新資訊；不准有純粹湊時間的步驟。〔R1, R6, R14〕
H9 跑腿式任務至少要有一次「預期被改變」（東西不在、委託人說謊、要先幫別人），或做成門與鑰匙的連鎖。〔R15, R14〕
H10 先讓玩家看到問題，再給解法；解法需要的物品在需要前就能取得，而且不能永久錯過。〔R1, R15〕
H11 支線是完整的小故事（開端、轉折、結局），用不同的語氣映照主題，適時打斷主線的節奏，並影響尾聲。〔R14〕
H12 把關鍵資訊藏在場景裡讓玩家調查拼湊（日記、擺設、告示），而不是由人物長篇說明。〔R6, R5, R4, R19〕
H13 擺設與伏筆都要有意義：前面讓玩家注意到的物品或台詞，後面一定要回收。〔R5, R6〕
H14 重要抉擇前先講清楚代價；選完立刻給一個小回應，之後再回收一次延遲的後果（用開關記住）。〔R6, R7, R9〕
H15 抉擇是沒有標準答案的兩難；不做只有一個合理選項的假抉擇，也不做「選錯就卡關或死掉」。〔R6, R9〕
H16 核心夥伴與主要人物要少而深：各有明確的專長與主題鉤子，對玩家的選擇與場景有反應，背景故事分章慢慢揭露；村民也要有自己的小故事，讓多聊天有收穫。〔R11, R12〕
H17 提示要分層：先輕推一下、再重述已出現的線索、最後才直接說答案；每則提示都寫出具體的物件與地點（用多個事件頁依卡關程度切換）。〔R16, R15, R1〕
H18 結局回收累積的關係與選擇開關，讓不同狀態導向意義不同的結局，並用尾聲點名回應。〔R8, R7〕
### 常見盲點（AI 最容易犯，製作與審查都要特別檢查）
X1 用說明代替參與：人物長篇講背景，玩家只能一直按「繼續」。〔R19, R5, R6〕
X2 重複：好幾個人物輪流講同一件事，或每章都是同一種衝突。〔R6, R17〕
X3 填充：為了拉長時間加跑腿或沒有劇情意義的謎題。〔R1, R14, R6〕
X4 細節過度：堆砌之後不會回收的設定與擺設。〔R6, R5〕
X5 抉擇無效：分支馬上合流、沒有開關記住，玩家感覺選了等於白選。〔R7, R9, R10〕
X6 倒序謎題或猜謎題：解法出現在問題之前，或只能靠亂試。〔R1〕
X7 只有一種語氣：缺少幽默與反差，支線和主線一樣沉重。〔R12, R14〕
X8 為了製造驚喜讓主角突然背叛玩家。〔R18〕`;

