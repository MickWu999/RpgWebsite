export const DESIGN_GUIDE = `## 敘事設計準則（請逐條遵守）
### 結構與分支
A1 用「分支與瓶頸」當骨架：主線切成 2～4 個瓶頸（任務目標），分支在下一個瓶頸前會合；會合點至少一句台詞依先前分支不同。
A2 禁止整局時間洞穴：分支最多 2 層就要會合，只有結局段落可以完全分開。
A3 後果記在旗標上：每個主要選擇設一個有名稱的旗標；後續對話與結局讀旗標判斷。每個旗標設定後至少被讀取 1 次（不能有只寫不讀的死旗標）。
A4 蒐集型步驟不限順序；每個節點都走得到、沒有卡關。
### 選擇設計
B1 選擇要有意圖：玩家選之前看得出利害、方向與代價，不做盲選。
B2 至少一個真正的兩難：兩邊都是玩家在乎的東西，沒有明顯正解，雙方立場說明量相近。
B3 選項彼此在語氣、意圖或價值上不同，並回應 NPC 上一句話，不要全是問句。
B4 主要選擇全局 2～4 個，放在戲劇高點；其他是風味選擇，但也要換到一句專屬回應。
B5 每個主要選擇都要在「後續另一段對話」與「結局文字」中各被回應一次。
### 任務設計
C1 每個任務一個終點，寫清楚交付者、他為什麼在乎、完成條件。
C2 不做單純跑腿：每個任務至少 1 個轉折或新資訊，改變玩家知道的事或想做的事。
C3 每個物品都要有敘事脈絡，並在對話或條件中出現；不加無意義的系統。
C4 相鄰目標換人或換地點；至少 1 個目標有 2 種解法（例如說服或交出物品），各有台詞。
### NPC 與對話
D1 每位 NPC 有一句話說得出的「想要什麼」、固定的說話特徵（用詞、句長、口頭禪），並牽涉任務或結局。
D2 對話圍繞玩家的目標推進，NPC 不要只自我介紹。
D3 每個對話框 2～3 句；關鍵資訊不放第一句；重大揭露後給玩家回應選項。
D4 不重複資訊；每位主要 NPC 至少 1 句台詞依旗標改變，讓人覺得「他記得我做過的事」。
D5 長對話要有一個直接推進主線的選項。
### 節奏
E1 10 分鐘預算：3～5 個段落，每段推進一個目標或揭露一個資訊。
E2 關鍵資訊用專屬對話傳達；情感高點前後留一個短停頓節點。
E3 交給環境說的就不用台詞說：至少 2 個可調查的人事物（例如路人、告示）分擔背景說明。
### 結局
F1 結局由至少 2 個旗標的組合決定，不能只看最後一個選擇。
F2 結局文字點名回應至少 2 個玩家做過的決定；各結局在意義上不同（誰得到什麼、付出什麼），不是同一結果的好壞版本。
F3 結局回答開場的主要問題，並交代每位主要 NPC 的去向（各至少一句）。`;

