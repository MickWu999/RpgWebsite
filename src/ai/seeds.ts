export type Seed = { rule: string; role: string; question: string; tone: string };

/** 抽出 n 組互不重複的種子 */
export function drawSeeds(n = 3, random: () => number = Math.random): Seed[] {
  const pick = <T extends readonly string[]>(deck: T, used: Set<string>) => {
    const left = deck.filter((x) => !used.has(x));
    const v = left[Math.floor(random() * left.length)];
    used.add(v);
    return v;
  };
  const used = new Set<string>();
  return Array.from({ length: n }, () => ({
    rule: pick(SEED_DECKS.rule, used),
    role: pick(SEED_DECKS.role, used),
    question: pick(SEED_DECKS.question, used),
    tone: pick(SEED_DECKS.tone, used),
  }));
}
